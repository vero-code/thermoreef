import { type InterventionResponse } from '../../data/reefs';

export function getUrgencyColor(urgency: string): string {
  const u = urgency.toLowerCase();
  if (u.includes('critical') || u.includes('immediate')) return '#ef4444';
  if (u.includes('high')) return '#f97316';
  if (u.includes('watch')) return '#eab308';
  return '#10b981';
}

export function formatProtocolAsText(data: InterventionResponse): string {
  const { protocol, stress, coordinates } = data;

  return `
THERMOREEF EMERGENCY INTERVENTION PROTOCOL
==========================================
Reef: ${protocol.reef_name || 'Reef #' + protocol.reef_id}
Coordinates: ${coordinates.lat.toFixed(4)}, ${coordinates.lng.toFixed(4)}
Urgency: ${protocol.urgency_level}
Intervention Window: ${protocol.intervention_window}
NOAA Status: BAA ${stress.baa} | DHW ${stress.dhw} °C-weeks | SST ${stress.sst} °C | Anomaly +${stress.tempAnomaly} °C

EXECUTIVE SUMMARY:
${protocol.executive_summary}

1. SHADING STRATEGY:
- Required: ${protocol.shading.needed ? 'YES' : 'NO'}
- Method: ${protocol.shading.recommended_method}
- Target Hours: ${protocol.shading.target_hours}
- Expected Cooling Delta: ${protocol.shading.expected_cooling_delta}
- Priority: ${protocol.shading.priority}

2. BIOLOGICAL TRIAGE:
- Species at Risk: ${protocol.triage.species_at_risk.join(', ') || 'None noted'}
- Broodstock Relocation: ${protocol.triage.donor_relocation ? 'RECOMMENDED' : 'NOT REQUIRED'}
- Nutritional/Antioxidant: ${protocol.triage.antioxidant_or_feeding}
- Action Items:
${protocol.triage.action_items.map((it, idx) => `  ${idx + 1}. ${it}`).join('\n')}

3. MONITORING & DISPATCH:
- Survey Frequency: ${protocol.monitoring.survey_frequency}
- Recommended Tools: ${protocol.monitoring.recommended_tools.join(', ')}
- Dispatch Notice: ${protocol.monitoring.alert_dispatch}

Generated by: ${protocol.generated_by || 'NVIDIA Nemotron via Nebius Token Factory'} (${protocol.model_used || 'Nemotron-3 Ultra'})
`.trim();
}
